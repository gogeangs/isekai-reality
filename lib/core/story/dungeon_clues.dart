/// 던전 층별 이야기 단서 (묶음 19 #7): 「왜 세계가 겹쳐졌는가」.
///
/// 층(1층·2층·3층·보스)마다 정령 대사 한 마디. 레벨이 오를수록 다음 장으로
/// 이어지고, Lv.11 레벨업 단서와 정령 이별이 첫 막의 끝이다.
/// 이별 뒤(펫)에는 나오지 않는다.
class DungeonClues {
  DungeonClues._();

  /// 장마다 [1층, 2층, 3층, 보스]
  static const chapters = <List<String>>[
    // 1장 (Lv.1~4): 잿빛 던전은 문이 억지로 열린 자리
    [
      '여기가 잿빛 던전이야. 바깥 안개랑 같은 냄새가 나.',
      '벽에 금이 가 있어. 누가 억지로 문을 연 자국 같아.',
      '아래에서 바람이 불어와. 저쪽 세계의 바람이야.',
      '저 녀석이 문 앞을 지키고 있어! 조심해!',
    ],
    // 2장 (Lv.5~6): 저쪽 세계는 빛이 꺼져 가고 있다
    [
      '벽 글씨가 조금 읽혀. 「빛이 모자라」…',
      '저쪽 세계는 빛이 꺼져 가고 있대. 그래서 이쪽으로 새어 나오는 걸까?',
      '몬스터들도 길을 잃은 거야. 빛을 따라 넘어왔다가 못 돌아간 거지.',
      '보스를 쓰러뜨리면 잿빛이 조금 걷혀. 너도 느껴져?',
    ],
    // 3장 (Lv.7~8): 정령은 문을 지키던 불씨였다
    [
      '나, 이 던전을 아는 것 같아. 아주 오래전에 지나간 적이 있어.',
      '생각났어. 나는 저쪽 세계에서 문을 지키던 불씨였어.',
      '문이 깨졌을 때 나는 이쪽으로 떨어졌고, 그래서 너를 만났어.',
      '이 겹침은 그냥 일어난 일이 아니야. 문이 깨진 데는 까닭이 있어.',
    ],
    // 4장 (Lv.9): 두 세계가 서로를 살리려고 겹쳤다
    [
      '각성자가 늘수록 문틈이 환해져. 너희 빛이 저쪽을 데우고 있어.',
      '저쪽 빛은 이쪽을, 이쪽 빛은 저쪽을 부르고 있었던 거야.',
      '그래서 세계가 겹쳐졌어. 서로를 살리려고.',
      '하지만 문이 이대로면 두 세계 다 흐려져. 누군가 고쳐야 해.',
    ],
    // 5장 (Lv.10~): 문을 고칠 수 있는 건 정령뿐 → Lv.11 이별
    [
      '요즘 여기 오면 마음이 이상해. 집에 가까워지는 기분이야.',
      '문을 고칠 수 있는 건 문지기 불씨뿐이래. 바로 나야.',
      '네가 강해져서 다행이야. 이제 너 혼자서도 괜찮을 거야.',
      '이 싸움이 끝나면… 아니야, 지금은 이기는 것만 생각하자!',
    ],
  ];

  /// 레벨에 맞는 장 (0부터)
  static int chapterOf(int level) => level <= 4
      ? 0
      : level <= 6
          ? 1
          : level <= 8
              ? 2
              : level <= 9
                  ? 3
                  : 4;

  /// [floor] 층(0부터, 마지막은 보스)의 단서. 이별 뒤엔 null
  static String? lineFor({
    required int level,
    required int floor,
    required int floors,
    required bool farewellDone,
  }) {
    if (farewellDone || floors <= 0) return null;
    final ch = chapters[chapterOf(level)];
    final i = floor >= floors - 1 ? 3 : floor.clamp(0, 2);
    return ch[i];
  }
}
